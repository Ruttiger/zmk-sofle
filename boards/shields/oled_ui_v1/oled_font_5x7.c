const uint8_t *oled_font_5x7_glyph(char ch)
{
	const size_t count = sizeof(oled_font_entries) /
			     sizeof(oled_font_entries[0]);

	if (ch >= 'a' && ch <= 'z' && ch != 'x') {
		ch = (char)(ch - ('a' - 'A'));
	}

	for (size_t i = 0; i < count; ++i) {
		if (oled_font_entries[i].ch == ch) {
			return oled_font_entries[i].rows;
		}
	}

	return oled_font_blank;
}
